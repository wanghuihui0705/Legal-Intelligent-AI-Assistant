# 构建快速查询集合，加速去重
SYNONYM_SET = set()
for vals in SYNONYM_MAP.values():
    SYNONYM_SET.update(vals)


def register_jieba_words():
    """把同义词的键和值都注册进 jieba，确保它们被切成一个整词而不是拆成单字。"""
    for k, vs in SYNONYM_MAP.items():
        jieba.add_word(k)
        for v in vs:
            jieba.add_word(v)


def expand_tokens(tokens: list) -> list:
    """
    输入 jieba 分词结果列表，返回扩充后的列表（原词 + 规范词，去重且保序）。
    :param tokens: jieba.lcut 得到的分词列表
    :return: 扩展后的 token 列表
    """
    expanded = tokens.copy()
    added = set(expanded)

    for t in tokens:
        norm_words = SYNONYM_MAP.get(t, [])
        for word in norm_words:
            if word not in added:
                expanded.append(word)
                added.add(word)
    return expanded


def text_to_expanded_tokens(text: str):
    """
    便捷入口：原始文本 → 分词 → 同义词扩展
    建索引、用户查询都统一调用这个函数！
    """
    seg = jieba.lcut(text)
    return expand_tokens(seg)


